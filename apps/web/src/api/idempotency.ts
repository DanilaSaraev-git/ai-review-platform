/**
 * Ключ идемпотентности вырабатывается по намерению пользователя, а не по
 * вызову (решение R-05, FR-012, SC-009).
 *
 * Намерение — это конкретная операция с конкретным содержимым: создать запуск
 * с этим документом, контекстом и профилями; отправить этот вопрос при этой
 * ревизии диалога. Пока намерение не изменилось, повторная отправка использует
 * тот же ключ, и сервис воспроизводит исходный результат, а не создаёт второй
 * запуск — ни при двойном нажатии, ни при повторе после разрыва связи.
 * Изменившееся содержимое даёт другое намерение и другой ключ.
 */
/**
 * Ключ выводится из намерения детерминированно, а не выдаётся случайно.
 *
 * Случайный ключ, сохранённый только в памяти вкладки, терялся бы при
 * перезагрузке страницы, и повторная отправка того же намерения создала бы
 * второй запуск. Детерминированная выработка делает ключ одинаковым при любом
 * повторе того же намерения — в том числе после перезагрузки (FR-012, SC-009).
 */
function hash64(value: string): string {
  // Две независимые свёртки FNV-1a дают 128 бит: этого достаточно, чтобы
  // разные намерения не сталкивались в пределах рабочего пространства.
  let first = 0x811c9dc5;
  let second = 0x01000193;
  for (let index = 0; index < value.length; index += 1) {
    const code = value.charCodeAt(index);
    first ^= code;
    first = Math.imul(first, 0x01000193) >>> 0;
    second ^= code + index;
    second = Math.imul(second, 0x85ebca6b) >>> 0;
  }
  return `${first.toString(16).padStart(8, '0')}${second.toString(16).padStart(8, '0')}`;
}

/** Стабильный ключ для намерения: одно намерение — один и тот же ключ. */
export function idempotencyKeyFor(intent: string): string {
  return `idem-${hash64(intent)}${hash64(`${intent}#salt`)}`;
}

/**
 * Намерение по самому запросу: метод, путь и тело.
 * Тело доступно в mutator, поэтому отдельные конструкторы намерений для каждой
 * операции не нужны — правило одно и применяется единообразно.
 */
export function requestIntent(method: string, pathname: string, body: BodyInit | null | undefined): string {
  const payload = typeof body === 'string' ? body : body === undefined || body === null ? '' : '[binary]';
  return `${method.toUpperCase()} ${pathname} ${payload}`;
}

